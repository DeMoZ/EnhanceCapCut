#!/usr/bin/env python3
"""Writes src/EnhanceCapCut.Subtitles/UnicodeNfkd.Data.cs: the Unicode NFKD decompositions and combining classes
that the voice cloning tokenizer needs. The app runs with InvariantGlobalization, where .NET's string.Normalize
does nothing, so the tables are compiled in. Run with the Python whose Unicode version you want:
    python3 windows/scripts/make-nfkd.py
"""
import pathlib
import unicodedata

decompositions, classes = [], []
for cp in range(0x110000):
    if 0xD800 <= cp <= 0xDFFF:
        continue
    c = chr(cp)
    if not 0xAC00 <= cp <= 0xD7A3:  # Hangul syllables are decomposed by formula
        d = unicodedata.normalize("NFKD", c)
        if d != c:
            decompositions.append(f"{cp:X}:" + ",".join(f"{ord(x):X}" for x in d))
    if unicodedata.combining(c):
        classes.append(f"{cp:X}:{unicodedata.combining(c):X}")


def literal(entries, indent="        "):
    lines, line = [], ""
    for e in entries:
        if len(line) + len(e) + 1 > 110:
            lines.append(line)
            line = ""
        line += e + ";"
    lines.append(line)
    return ("\n" + indent + "+ ").join(f'"{l}"' for l in lines)


out = f"""// Generated by windows/scripts/make-nfkd.py from Unicode {unicodedata.unidata_version}. Do not edit.
namespace EnhanceCapCut.Subtitles;

static partial class UnicodeNfkd
{{
    /// <summary>Code point → its full NFKD decomposition, hex, "cp:d1,d2;" (Hangul syllables excluded).</summary>
    const string Decompositions =
        {literal(decompositions)};

    /// <summary>Code point → canonical combining class, hex, "cp:class;" (class 0 omitted).</summary>
    const string CombiningClasses =
        {literal(classes)};
}}
"""
path = pathlib.Path(__file__).resolve().parent.parent / "src/EnhanceCapCut.Subtitles/UnicodeNfkd.Data.cs"
path.write_text(out, encoding="utf-8")
print(f"{path}: {len(decompositions)} decompositions, {len(classes)} combining classes")
